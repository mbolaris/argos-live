#!/usr/bin/env python3
"""Build (or check) a deterministic Shakedown suite and fault-card sidecar from a recipe."""
import argparse
import importlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'runtime'))

from argoslive.shakedown import generators


def _pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate recipe key: {key}')
        result[key] = value
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--recipe', required=True, type=Path, help='JSON recipe file')
    parser.add_argument('--output-dir', type=Path, help='directory for <suite>-<version>.json files')
    parser.add_argument('--check', action='store_true', help='compare generated bytes with checked-in files')
    parser.add_argument('--generator-module', action='append', default=[],
                        help='import a generator module before building (may be repeated)')
    args = parser.parse_args()
    if args.check == (args.output_dir is not None):
        parser.error('choose exactly one of --check or --output-dir')
    try:
        for module in args.generator_module:
            importlib.import_module(module)
        with args.recipe.open('r', encoding='utf-8') as stream:
            recipe = json.load(stream, object_pairs_hook=_pairs)
        built = generators.build_bytes(recipe)
        stem = f"{recipe['suite']}-{recipe['version']}"
        expected = {'form': ROOT / 'runtime' / 'argoslive' / 'data' / 'ability' / f'{stem}.json',
                    'sidecar': ROOT / 'runtime' / 'argoslive' / 'data' / 'shakedown' / 'sidecars' / f'{stem}.json'}
        if args.check:
            mismatches = [str(path) for key, path in expected.items()
                          if not path.is_file() or path.read_bytes() != built[key]]
            if mismatches:
                raise ValueError('Generated files differ or are missing: ' + ', '.join(mismatches))
            print(json.dumps({'suite': stem, 'form_sha256': built['form_sha256'],
                              'sidecar_sha256': built['sidecar_sha256']}, sort_keys=True))
            return 0
        args.output_dir.mkdir(parents=True, exist_ok=True)
        (args.output_dir / f'{stem}.json').write_bytes(built['form'])
        (args.output_dir / f'{stem}.sidecar.json').write_bytes(built['sidecar'])
        print(json.dumps({'suite': stem, 'form_sha256': built['form_sha256'],
                          'sidecar_sha256': built['sidecar_sha256']}, sort_keys=True))
        return 0
    except (OSError, ValueError, TypeError, KeyError, json.JSONDecodeError) as exc:
        print(f'shakedown-build-form: {exc}', file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
